/**
 * Get translation for a key in a specific language
 */
export function t(key: keyof typeof translations, language: string = 'en'): string {
  const translationGroup = translations[key];
  if (!translationGroup) {
    return key;
  }

  const lang = language.toLowerCase();
  return (translationGroup as any)[lang] || (translationGroup as any)['en'] || key;
}

/**
 * Get all translations for a key
 */
export function getAllTranslations(key: keyof typeof translations): Record<string, string> {
  return translations[key] as any;
}

export default {
  translations,
  t,
  getAllTranslations,
};
